CREATE DATABASE nexa_quest;
USE nexa_quest;

CREATE TABLE IF NOT EXISTS Usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha VARCHAR(255) NOT NULL,
  tipo ENUM('jogador', 'administrador') NOT NULL DEFAULT 'jogador',
  pontos_xp INT NOT NULL DEFAULT 0,
  nivel INT NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Missaos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT NOT NULL,
  jornada VARCHAR(255) NOT NULL,
  dificuldade ENUM('facil', 'medio', 'dificil') NOT NULL DEFAULT 'facil',
  pontos_recompensa INT NOT NULL DEFAULT 100,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ProgressoMissaos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  status ENUM('em_andamento', 'concluida') NOT NULL DEFAULT 'concluida',
  pontos_ganhos INT NOT NULL,
  data_conclusao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  usuario_id INT NOT NULL,
  missao_id INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_progresso_usuario FOREIGN KEY (usuario_id) REFERENCES Usuarios(id) ON DELETE CASCADE,
  CONSTRAINT fk_progresso_missao FOREIGN KEY (missao_id) REFERENCES Missaos(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Conquista (
  id INT AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(255) NOT NULL,
  descricao VARCHAR(255) NOT NULL,
  icone VARCHAR(50) NOT NULL DEFAULT '🏆',
  xp_necessario INT NOT NULL DEFAULT 100,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
